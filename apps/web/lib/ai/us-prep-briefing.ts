function pickPrimaryScenario(matched: Scenario[]): Scenario | null {
  if (matched.length === 0) return null;
  return [...matched].sort((a, b) => b.priority - a.priority)[0] ?? null;
}

function clinicalFromScenario(s: Scenario): string[] {
  if (s.clinicalActions?.length) return s.clinicalActions;
  return unique([...s.attention.slice(0, 2), ...s.labs.slice(0, 2), ...s.treatment.slice(0, 1)]);
}

