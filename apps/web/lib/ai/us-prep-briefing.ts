export function buildUsPrepBriefing(input: UsPrepBriefingInput): UsPrepBriefingResult {
  const complaints = input.complaints.trim();
  const domain: UsPrepDomain = input.domain ?? "both";
  const role: DoctorVisitRole = input.role ?? "obgyn_us";
  const visit = input.visitContext?.trim() ?? "";
  const haystack = `${complaints}\n${visit}`;

  const matched = SCENARIOS.filter((s) => domainAllows(s, domain) && s.match.test(haystack));
  const primary = pickPrimaryScenario(matched);
  const secondaryFlags = matched
    .filter((s) => s.id !== primary?.id)
    .sort((a, b) => b.priority - a.priority)
    .slice(0, 1);

  const sources = primary ? [primary] : [];
  const flagSources = primary ? [primary, ...secondaryFlags] : [];

  const clinicalChecklistRu = unique(
    sources.length
      ? sources.flatMap((s) => clinicalFromScenario(s))
      : FALLBACK_CLINICAL,
  ).slice(0, 7);

  const ultrasoundQuestionsRu = unique(
    sources.length ? sources.flatMap((s) => s.questions) : FALLBACK_QUESTIONS,
  ).slice(0, 8);

  const attentionPointsRu = unique(
    sources.length ? sources.flatMap((s) => s.attention) : FALLBACK_ATTENTION,
  ).slice(0, 6);

  const labsAndSmearsRu = unique(
    sources.length ? sources.flatMap((s) => s.labs) : FALLBACK_LABS,
  ).slice(0, 6);

  const treatmentContextRu = unique(
    sources.length ? sources.flatMap((s) => s.treatment) : FALLBACK_TREATMENT,
  ).slice(0, 5);

  const redFlagsRu = unique(flagSources.flatMap((s) => s.redFlags)).slice(0, 6);

  const showClinical = role === "obgyn" || role === "obgyn_us";
  const showUs = role === "us" || role === "obgyn_us";

  const clinicalOut = showClinical ? clinicalChecklistRu : [];
  const usOut = showUs ? ultrasoundQuestionsRu : [];
  const labsOut = showClinical ? labsAndSmearsRu : labsAndSmearsRu.slice(0, 2).map((l) => `Для направившего АГ: ${l}`);
  const treatOut = showClinical
    ? treatmentContextRu
    : ["Не назначать лечение из протокола УЗИ — только эхо-находки и срочность маршрута."];

  const attentionOut = showUs
    ? attentionPointsRu
    : attentionPointsRu.filter((a) => !/фигo|o-rads|sliding|срез|эхо/i.test(a)).slice(0, 4);

  const primaryChecklistRu =
    role === "us"
      ? unique([...attentionOut.slice(0, 3), ...usOut.slice(0, 5)]).slice(0, 8)
      : role === "obgyn"
        ? unique([...clinicalOut.slice(0, 5), ...labsOut.slice(0, 3)]).slice(0, 8)
        : unique([...clinicalOut.slice(0, 4), ...usOut.slice(0, 4)]).slice(0, 8);

  const moduleMap = new Map<string, { href: string; label: string }>();
  for (const s of sources) {
    for (const m of s.modules) moduleMap.set(m.href, m);
  }
  if (moduleMap.size === 0) {
    moduleMap.set("/ai/consultants/gynecology", {
      href: "/ai/consultants/gynecology",
      label: "Помощник · нозологии",
    });
  }

  const guidelineQuery = primary?.guidelineQuery || complaints.slice(0, 120) || "гинекология";
  const relatedGuidelines = searchGuidelinesLocal(guidelineQuery, 4);

  const titleRu = primary
    ? `${DOCTOR_VISIT_ROLE_LABELS[role]} · ${primary.labelRu}`
    : `${DOCTOR_VISIT_ROLE_LABELS[role]} · общий фокус по жалобам`;

  const complaintSummaryRu = [
    complaints ? `Жалобы: ${complaints.slice(0, 280)}${complaints.length > 280 ? "…" : ""}` : "Жалобы не указаны.",
    visit ? `Контекст: ${visit}` : null,
    primary ? `Сценарий: ${primary.labelRu}.` : "Сценарий не распознан — уточните жалобы.",
  ]
    .filter(Boolean)
    .join(" ");

  return {
    audience: "doctor_only",
    role,
    roleLabelRu: DOCTOR_VISIT_ROLE_LABELS[role],
    titleRu,
    complaintSummaryRu,
    primaryChecklistRu,
    clinicalChecklistRu: clinicalOut,
    ultrasoundQuestionsRu: usOut,
    attentionPointsRu: attentionOut,
    labsAndSmearsRu: showClinical ? labsOut : labsOut.slice(0, 3),
    treatmentContextRu: treatOut,
    redFlagsRu,
    relatedGuidelines,
    suggestedModules: [...moduleMap.values()].slice(0, 5),
    primaryScenarioId: primary?.id ?? null,
    disclaimerRu: DISCLAIMER,
    pipeline: "us-prep-briefing-v2",
  };
}
