function domainAllows(scenario: Scenario, domain: UsPrepDomain): boolean {
  if (domain === "both") return true;
  return scenario.domains.includes(domain) || scenario.domains.includes("both");
}

function unique(items: string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of items) {
    const key = item.trim();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(key);
  }
  return out;
}

