export function getPelvisMapSteps(): PelvisMapStep[] {
  return [...PELVIS_MAP_STEPS].sort((a, b) => a.order - b.order);
}

export function buildProtocolFromPhraseIds(selectedIds: string[]): string {
  const byId = new Map<string, PelvisMapPhrase>();
  for (const step of PELVIS_MAP_STEPS) {
    for (const p of step.phrases) byId.set(p.id, p);
  }
  const lines: string[] = [];
  for (const id of selectedIds) {
    const phrase = byId.get(id);
    if (phrase) lines.push(phrase.text);
  }
  if (lines.length === 0) return "";
  return `${lines.join("\n\n")}\n\n${PELVIS_MAP_DISCLAIMER}`;
}
