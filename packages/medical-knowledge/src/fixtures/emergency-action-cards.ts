function sid(n: number): string {
  return `cccccccc-cccc-cccc-cccc-${String(n).padStart(12, "0")}`;
}

function sec(
  n: number,
  sectionType: CanonicalKnowledgeArticle["sections"][number]["sectionType"],
  title: string,
  content: string,
  sortOrder: number,
) {
  return { id: sid(n), sectionType, title, content, sortOrder };
}

function nSource(pageStart: number, pageEnd: number, chapter?: string): SourceCitationPublic {
  return {
    ...FELDSCHER_2025_SOURCE,
    id: `bbbbbbbb-bbbb-bbbb-bbbb-${String(pageStart).padStart(12, "0")}`,
    pageStart,
    pageEnd,
    chapter: chapter ?? FELDSCHER_2025_SOURCE.chapter,
  };
}

function guide(input: {
  n: number;
  slug: string;
  title: string;
  aliases: string[];
  summary: string;
  pageStart: number;
  pageEnd: number;
  krTopic: string;
  symptoms: string;
  diagnostics: string;
  steps: string;
  medications: string;
  doNot: string;
  escalation: string;
}): CanonicalKnowledgeArticle {
  const base = nSource(input.pageStart, input.pageEnd);
  const b = input.n * 20;
  return {
    id: sid(1000 + input.n),
    slug: input.slug,
    title: input.title,
    specialty: "emergency",
    topicType: "emergency_guide",
    summary: input.summary,
    version: "1.0.0-guide",
    aliases: input.aliases,
    sections: [
      sec(b + 1, "symptoms", "Симптомы / на что смотреть", input.symptoms, 0),
      sec(b + 2, "diagnostics", "Анализы и обследования", input.diagnostics, 1),
      sec(b + 3, "action_steps", "Что делать (1-2-3)", input.steps, 2),
      sec(b + 4, "medications", "Препараты (справочно)", input.medications, 3),
      sec(b + 5, "do_not", "Чего не делать", input.doNot, 4),
      sec(b + 6, "escalation", "Эскалация / госпитализация", input.escalation, 5),
      sec(
        b + 7,
        "education",
        "Источник и КР",
        `Справочник фельдшера 2025, стр. ${input.pageStart}–${input.pageEnd}. КР: ${input.krTopic}. ${KR_SHELF_NOTE}`,
        6,
      ),
      sec(
        b + 8,
        "warning",
        "Дисклеймер",
        "Справочный CDS SonoGyn Pro. Не диагноз и не замена осмотра. Дозы и показания — только по актуальным КР МЗ РФ / локальному протоколу.",
        7,
      ),
    ],
    sources: [base],
  };
}

