export function getScenario(id: string): ClinicalScenario | undefined {
  return CLINICAL_SCENARIOS.find((s) => s.id === id);
}

export function scenariosForReasons(reasonIds: string[]): ClinicalScenario[] {
  const ids = new Set<string>();
  for (const r of reasonIds) {
    const reason = VISIT_REASONS.find((x) => x.id === r);
    reason?.scenarioIds.forEach((id) => ids.add(id));
  }
  return CLINICAL_SCENARIOS.filter((s) => ids.has(s.id));
}
